"""Stabiliser rank: the smallest number of stabiliser states that add up to a magic state.

    python tools/view/stabiliser_rank.py            the ranks, exactly
    python tools/view/stabiliser_rank.py --check    grade the machinery first

WHY THIS IS THE MEASURE THAT MATTERS HERE. This family spent a session establishing that MAGIC and
not entanglement is the resource: a perfect matching across a cut of 4096 qubits holds 2048 bits of
entanglement in a megabyte, Clifford gates conserve magic to 6.66e-16, and the T gate is exactly
free on the exact simulator at distance 0. All of that says what is cheap. None of it says what the
expensive thing COSTS.

Stabiliser rank does. Write a state as a sum of k stabiliser states and a Gottesman-Knill style
simulation runs in time proportional to k, because each term is separately cheap. So the minimum k,
written chi, IS the classical simulation cost of that state, and the exponential this family has
been circling lives in how chi grows with the number of T gates. That is the wall, stated as a
number rather than as a worry.

NO TOLERANCES ANYWHERE, AND THAT IS FORCED RATHER THAN PREFERRED. chi is the answer to "is this
vector in the span of those", and a span membership decided by a float comparison is a span
membership decided by a threshold somebody chose. Every amplitude in this file is an exact element
of Z[zeta_8], the ring generated by zeta = exp(i pi / 4):

    unnormalised H = [[1, 1], [1, -1]]      integer
    unnormalised S = diag(1, i)             i = zeta^2
    unnormalised CZ = diag(1, 1, 1, -1)     integer
    unnormalised |T> = (1, zeta)            the only place zeta itself enters

Normalisation is dropped throughout because chi is a question about SPANS, and a span does not care
about scale. That keeps every amplitude an algebraic integer, and linear algebra over the degree-4
field Q(zeta_8) then decides membership exactly. A rank is an integer or the machinery is broken;
there is no third outcome to tune.

WHAT IS AND IS NOT CLAIMED. The ranks below are computed by exhaustive search over the stabiliser
states at one, two and three qubits, whose counts are 6, 60 and 1080 and must match the closed form
2^n prod_{k=1}^{n} (2^k + 1) or the enumeration is wrong. Exhaustive means exhaustive at k = 1 and
k = 2; at three qubits the triples number 209 million and are not enumerated, a three-qubit
answer larger than 2 is reported as a LOWER BOUND and labelled as one.
"""

