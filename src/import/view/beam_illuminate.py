"""Real chain entropy streamed through the beams, and whether it illuminates the object.

    python tools/view/beam_illuminate.py --check
    python tools/view/beam_illuminate.py            the four light sources, graded on recovery
    python tools/view/beam_illuminate.py --entropy   what the chain is worth as a noise source

THE CLAIM UNDER TEST

Douglas, 2026-09-12: "if you want entropy, lock onto a noise source, like the blockchain and use
the from sound script to turn it into entropy", "you can stream that through your neutrinos", "so
it literally shoots entropy to illuminate pretend objects in our storage universe."

beam_rows.py already carries the illumination model in its own words: what stops the carried beam
is the bit being set, what casts the shadow is the stopping, and the pattern on the wall is the
state. So the beams were always rays. What was missing is a real light source instead of a
synthetic seed.

WHERE THE ENTROPY ACTUALLY ENTERS, WHICH IS THE PART THAT HAD TO BE GOT RIGHT

The obvious reading is to modulate each beam's intensity. That would be wrong and it is worth
saying why: scaling the rows of a matrix by a diagonal cannot change its rank, an intensity
pattern would leave the reading's reach untouched however random it was. The experiment would
measure nothing.

The entropy has to choose WHERE THE BEAMS POINT. Direction decides which sources a ray passes, so
it decides what the shadow can resolve. That makes the light source a property of the geometry
rather than a scaling, and it makes the claim falsifiable:

    ILLUMINATION WORKS      the object is recovered from its shadows
    ILLUMINATION FAILS      the shadows do not determine the object

FOUR SOURCES, AND TWO OF THEM ARE CONTROLS

    chain       real block headers from the verified corpus, hashed into directions
    csprng      an ideal source, which is the upper bound any real source is graded against
    degenerate  every beam pointed the same way. NO ENTROPY AT ALL. This must FAIL, and if it
                recovers the object then direction never mattered and the whole claim is empty.
    golden      the structured placement beam_rows.py already uses, for reference

A NULL HERE WOULD BE THE DEGENERATE ROW RECOVERING THE OBJECT. That is the outcome that would
refute the idea, so it is run rather than assumed.
"""

