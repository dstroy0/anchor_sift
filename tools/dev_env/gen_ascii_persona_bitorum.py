def num(c):
    return 0x30 <= c <= 0x39


def upper(c):
    return 0x41 <= c <= 0x5A


def lower(c):
    return 0x61 <= c <= 0x7A


def alpha(c):
    return upper(c) or lower(c)


def alnum(c):
    return alpha(c) or num(c)


def space(c):
    return c == 0x20 or 0x09 <= c <= 0x0D


def punct(c):
    return 0x21 <= c <= 0x7E and not alnum(c)


def hexd(c):
    return num(c) or (0x41 <= c <= 0x46) or (0x61 <= c <= 0x66)


def prnt(c):
    return 0x20 <= c <= 0x7E


def ctrl(c):
    return c < 0x20 or c == 0x7F


