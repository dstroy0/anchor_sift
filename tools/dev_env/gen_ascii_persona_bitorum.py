    ("UPPER", upper, "A-Z"),
    ("LOWER", lower, "a-z"),
    ("HEX", hexd, "0-9 A-F a-f"),
    ("PUNCT", punct, "printable, not alphanumeric, not space"),
    ("SPACE", space, "space tab newline vtab formfeed return"),
    ("CTRL", ctrl, "below space, and DEL"),
    ("PRINT", prnt, "space through ~"),
